@lru_cache(maxsize=12)
def generate(model, key, scenario):
    prompt = SCENARIOS[scenario][2]
    payload = {
        "system_instruction": {"parts": [{"text": "You write educational examples for a software portfolio. Answer in plain text, at most 90 words. Do not diagnose, recommend treatment, give individualized advice, or invent details."}]},
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {"maxOutputTokens": 512},
    }
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"
    req = Request(url, data=json.dumps(payload).encode(), headers={
        "Content-Type": "application/json", "x-goog-api-key": key,
    })
    with urlopen(req, timeout=18) as response:
        result = json.load(response)
    parts = result.get("candidates", [{}])[0].get("content", {}).get("parts", []) if result.get("candidates") else []
    answer = "\n".join(p["text"] for p in parts if p.get("text") and not p.get("thought")).strip()
    if not answer:
        raise ValueError("Empty model response")
    return answer


