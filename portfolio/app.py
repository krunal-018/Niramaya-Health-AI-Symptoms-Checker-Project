@app.post("/api/scenario")
def scenario():
    data = request.get_json(silent=True)
    name = data.get("scenario") if isinstance(data, dict) else None
    if not isinstance(name, str) or name not in SCENARIOS:
        return jsonify(error="Choose one of the sample scenarios."), 400
    if data.get("mode") == "sample":
        return jsonify(answer=SCENARIOS[name][3], source="Sample response")
    key = os.getenv("GEMINI_API_KEY")
    model = os.getenv("GEMINI_MODEL", "gemini-2.5-flash-lite")
    if not key or not re.fullmatch(r"[A-Za-z0-9._-]+", model):
        return jsonify(error="Live AI is unavailable. Choose Sample mode to continue."), 503
    try:
        return jsonify(answer=generate(model, key, name), source="Generated by Gemini")
    except HTTPError as error:
        if error.code == 429:
            return jsonify(error="The AI quota is busy. Try again later or switch to Sample mode."), 429
        return jsonify(error="The AI provider could not respond. Try Sample mode."), 502
    except (OSError, ValueError):
        return jsonify(error="The AI provider could not respond. Try Sample mode."), 502


